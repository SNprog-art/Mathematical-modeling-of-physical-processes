# =============================================================================
# Численное дифференцирование сеточных функций
# -----------------------------------------------------------------------------
# Функция:  y = 0.5 * sin(2x)
# Отрезок:  x ∈ [1; 6]
# Шаг:      h = 0.2
#
# Сравниваются четыре численные формулы дифференцирования:
#   1) правая разность         (1-й порядок точности, O(h))
#   2) левая разность          (1-й порядок точности, O(h))
#   3) центральная разность    (2-й порядок точности, O(h^2))
#   4) формула 4-го порядка    (4-й порядок точности, O(h^4))
#
# Эталон для сравнения — аналитическая производная, полученная символьно
# с помощью библиотеки SymPy:  dy/dx = cos(2x)
#
# Критерий качества — относительное СКО (в процентах) между численной
# производной и аналитической.
# =============================================================================

import sympy as sym          # символьные вычисления
import numpy as np           # численные массивы
import matplotlib.pyplot as plt  # построение графиков


# -----------------------------------------------------------------------------
# 1. Символьное (аналитическое) дифференцирование
# -----------------------------------------------------------------------------
# Определяем символьную переменную xs и функцию ys(xs).
# Метод .diff(xs) возвращает аналитическую производную функции.
# Ожидаемый результат: dys(x)/dx = 1.0 * cos(2*xs)
# -----------------------------------------------------------------------------
xs = sym.Symbol('xs')                # символьная переменная
ys = 0.5 * sym.sin(2 * xs)           # исходная функция
dys_dxs = ys.diff(xs)                # аналитическая производная
print("dys(x)/dx =", dys_dxs)


# -----------------------------------------------------------------------------
# 2. Создание сеточной функции
# -----------------------------------------------------------------------------
# Формируем массив узлов x[i] и значений функции y[i] в этих узлах.
# Используется равномерная сетка с шагом hx = 0.2.
# -----------------------------------------------------------------------------
def f(x):
    """Численная реализация исходной функции y = 0.5*sin(2x)."""
    return 0.5 * np.sin(2 * x)

a, b = 1, 6                       # границы отрезка [a, b]
hx = 0.2                          # шаг сетки
n = int((b - a) / hx) + 1         # число узлов (21 узел)

x = np.zeros(n)                   # массив узлов
y = np.zeros(n)                   # массив значений функции

x[0] = a                          # первый узел
y[0] = f(x[0])                    # значение функции в первом узле

# Заполняем остальные узлы и значения функции
for i in range(1, n):
    x[i] = x[i - 1] + hx
    y[i] = f(x[i])


# -----------------------------------------------------------------------------
# 3. Аналитическая производная в узлах сетки
# -----------------------------------------------------------------------------
# Подставляем числовые значения x[i] в символьное выражение dys_dxs.
# ВАЖНО: float(...) — обязательно, иначе элементы массива dy_dx
# будут иметь тип object (SymPy-объекты), и дальнейшие операции NumPy
# (np.max, np.min, вычитание) могут дать некорректный результат.
# -----------------------------------------------------------------------------
dy_dx = np.zeros(n)
for i in range(n):
    dy_dx[i] = float(dys_dxs.subs(xs, x[i]))

# Проверка типа: должно быть float64
print("Тип dy_dx:", dy_dx.dtype)


# -----------------------------------------------------------------------------
# 4. Функция расчёта относительного СКО
# -----------------------------------------------------------------------------
# Считает среднеквадратичное отклонение численной производной dFp
# от аналитической dy_dx и нормирует его на размах аналитической
# производной (max - min). Результат — в процентах.
# -----------------------------------------------------------------------------
def calc_skop(dFp, dy_dx):
    """Возвращает относительное СКО численной производной (в %)."""
    sko = 0
    for i in range(len(dy_dx)):
        sko += (dy_dx[i] - dFp[i]) ** 2
    sko = np.sqrt(sko / len(dy_dx))                  # абсолютное СКО
    skop = 100 * sko / (np.max(dy_dx) - np.min(dy_dx))  # в процентах
    return skop


# -----------------------------------------------------------------------------
# 5. Правая разность (1-й порядок точности)
# -----------------------------------------------------------------------------
# Формула:  y'(x_i) ≈ (y[i+1] - y[i]) / h
# Применима для i = 0, ..., n-2.
# На последнем узле i = n-1 берём аналитическое значение (граничное условие).
# -----------------------------------------------------------------------------
dFp_right = np.zeros(n)
for i in range(0, n - 1):
    dFp_right[i] = (y[i + 1] - y[i]) / hx
dFp_right[n - 1] = dy_dx[n - 1]                      # эталон на правом краю

print("Правая разность:  СКО =", calc_skop(dFp_right, dy_dx))


# -----------------------------------------------------------------------------
# 6. Левая разность (1-й порядок точности)
# -----------------------------------------------------------------------------
# Формула:  y'(x_i) ≈ (y[i] - y[i-1]) / h
# Применима для i = 1, ..., n-1.
# На первом узле i = 0 берём аналитическое значение (граничное условие).
# -----------------------------------------------------------------------------
dFp_left = np.zeros(n)
dFp_left[0] = dy_dx[0]                               # эталон на левом краю
for i in range(1, n):
    dFp_left[i] = (y[i] - y[i - 1]) / hx

print("Левая разность:   СКО =", calc_skop(dFp_left, dy_dx))


# -----------------------------------------------------------------------------
# 7. Центральная разность (2-й порядок точности)
# -----------------------------------------------------------------------------
# Формула:  y'(x_i) ≈ (y[i+1] - y[i-1]) / (2h)
# Применима для i = 1, ..., n-2.
# На крайних узлах i = 0 и i = n-1 берём аналитические значения.
# -----------------------------------------------------------------------------
dFp_center = np.zeros(n)
dFp_center[0] = dy_dx[0]                             # эталон на левом краю
for i in range(1, n - 1):
    dFp_center[i] = (y[i + 1] - y[i - 1]) / (2 * hx)
dFp_center[n - 1] = dy_dx[n - 1]                     # эталон на правом краю

print("Центральная разность: СКО =", calc_skop(dFp_center, dy_dx))


# -----------------------------------------------------------------------------
# 8. Формула 4-го порядка точности
# -----------------------------------------------------------------------------
# Формула:  y'(x_i) ≈ (y[i-2] - 8*y[i-1] + 8*y[i+1] - y[i+2]) / (12h)
# Применима для внутренних узлов i = 2, ..., n-3.
# На четырёх крайних узлах (i = 0, 1, n-2, n-1) берём аналитические значения.
#
# ВАЖНО: знаки именно такие: (+1, -8, +8, -1).
# Если поменять знаки на противоположные, получится производная
# со знаком минус — на графике это будет выглядеть как «зигзаг».
# -----------------------------------------------------------------------------
dFp_4 = np.zeros(n)
dFp_4[0]     = dy_dx[0]                              # эталон
dFp_4[1]     = dy_dx[1]                              # эталон
dFp_4[n - 2] = dy_dx[n - 2]                          # эталон
dFp_4[n - 1] = dy_dx[n - 1]                          # эталон

for i in range(2, n - 2):
    dFp_4[i] = (y[i - 2] - 8 * y[i - 1] + 8 * y[i + 1] - y[i + 2]) / (12 * hx)

print("Формула 4-го порядка: СКО =", calc_skop(dFp_4, dy_dx))


# -----------------------------------------------------------------------------
# 9. Построение графиков
# -----------------------------------------------------------------------------
# Красные звёздочки   — аналитическая производная
# Чёрные звёздочки    — правая разность
# Синие звёздочки     — левая разность
# Зелёные звёздочки   — центральная разность
# Фиолетовые точки    — формула 4-го порядка (накладывается на красные)
# -----------------------------------------------------------------------------
plt.figure(figsize=(10, 6))
plt.title("dy(x)/dx")
plt.xlabel("x")
plt.ylabel("dy/dx")
plt.grid()

plt.plot(x, dy_dx,      "r*", label="Аналитическая производная")
plt.plot(x, dFp_right,  "k*", label="Правая разность")
plt.plot(x, dFp_left,   "b*", label="Левая разность")
plt.plot(x, dFp_center, "g*", label="Центральная разность")
plt.plot(x, dFp_4,      "m.", label="4-й порядок")

plt.legend()
plt.show()
