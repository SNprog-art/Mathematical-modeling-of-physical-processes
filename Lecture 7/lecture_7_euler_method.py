# =============================================================================
# Решение задачи Коши для дифференциального уравнения
# -----------------------------------------------------------------------------
# Уравнение:          dy/dx = x^3 - 2y
# Начальное условие:  y(0) = 0
# Отрезок:            x ∈ [0, 1]
# Шаг:                hx = 0.1  (затем уменьшается в 10 раз: hx = 0.01)
#
# Программа выполняет четыре задачи:
#   1) Находит аналитическое (символьное) решение с помощью SymPy
#   2) Визуализирует аналитическое решение на отрезке [0, 1]
#   3) Решает задачу Коши методом Эйлера и сравнивает с аналитикой
#   4) Повторяет расчёт при уменьшении шага в 10 раз (hx = 0.01)
# =============================================================================

import sympy as sym             # символьные вычисления
import numpy as np              # численные массивы
import matplotlib.pyplot as plt # построение графиков


# =============================================================================
# ЧАСТЬ 1. АНАЛИТИЧЕСКОЕ (СИМВОЛЬНОЕ) РЕШЕНИЕ
# =============================================================================

# ---------- 1.1. Определение переменных ----------
# xs — независимая переменная (символьная)
# ys — искомая функция, зависящая от xs
xs = sym.symbols('xs')
ys = sym.Function('ys')

# ---------- 1.2. Определение дифференциального уравнения ----------
# sym.Eq(левая_часть, правая_часть) — создаёт символьно записанное уравнение.
# ys(xs).diff(xs) — производная функции ys по переменной xs, то есть dy/dx.
equation = sym.Eq(ys(xs).diff(xs), xs**3 - 2*ys(xs))

# ---------- 1.3. Общее решение ----------
# sym.dsolve(equation) возвращает общее решение уравнения.
# В общем решении присутствует произвольная константа C1.
solution = sym.dsolve(equation)
print("Аналит. решение диф.ур.:", solution)

# ---------- 1.4. Частное решение с начальным условием ----------
# ics = {ys(0): 0} — задаёт начальное условие y(0) = 0.
# sym.dsolve сам подберёт значение константы C1 так, чтобы условие выполнялось.
nsolution = sym.dsolve(equation, ys(xs), ics={ys(0): 0})
print("Частное решение диф.ур. при ys(0) = 0:", nsolution)


# =============================================================================
# ЧАСТЬ 2. ПОСТРОЕНИЕ СЕТКИ И ВЫЧИСЛЕНИЕ АНАЛИТИЧЕСКОГО РЕШЕНИЯ В УЗЛАХ
# =============================================================================

# ---------- 2.1. Параметры расчёта ----------
a = 0                # левая граница отрезка
b = 1                # правая граница отрезка
hx = 0.01             # шаг интегрирования (в части 4 уменьшим его до 0.01)

# ---------- 2.2. Формирование массива узлов ----------
# n — общее число узлов, включая обе границы.
# Формула n = (b - a)/hx + 1 даёт корректное число точек при равномерном шаге.
n = int((b - a) / hx) + 1

x = np.zeros(n)      # массив значений независимой переменной
ya = np.zeros(n)     # массив аналитического решения в узлах
x[0] = a             # первый узел — левая граница

for i in range(1, n):
    x[i] = x[i - 1] + hx

# ---------- 2.3. Подстановка числовых значений в аналитическое решение ----------
# nsolution.rhs — правая часть уравнения (само выражение для y(xs)).
# .subs(xs, x[i]) — метод SymPy для подстановки значения xs = x[i].
# float(...) — обязательно, иначе ya[i] останется SymPy-объектом,
#              и NumPy не сможет корректно посчитать СКО.
for i in range(0, n):
    ya[i] = float(nsolution.rhs.subs(xs, x[i]))


# =============================================================================
# ЧАСТЬ 3. ЧИСЛЕННОЕ РЕШЕНИЕ МЕТОДОМ ЭЙЛЕРА
# =============================================================================
# Расчётная формула метода Эйлера:
#       y[i+1] = y[i] + h * f(x[i], y[i])
# где f(x, y) — правая часть дифференциального уравнения y' = f(x, y).
# =============================================================================

# ---------- 3.1. Правая часть уравнения ----------
def f(x_d, y_d):
    """Возвращает значение правой части уравнения y' = x^3 - 2y."""
    return x_d**3 - 2 * y_d

# ---------- 3.2. Массив для численного решения ----------
ye = np.zeros(n)
ye[0] = 0            # начальное условие y(0) = 0

# ---------- 3.3. Итерационный цикл Эйлера ----------
# На каждом шаге используем только текущее значение ye[i]
# (метод Эйлера — одношаговый).
for i in range(0, n - 1):
    ye[i + 1] = ye[i] + hx * f(x[i], ye[i])

# ---------- 3.4. Расчёт относительной погрешности ----------
# Сначала находим абсолютное СКО между аналитикой ya и методом ye,
# затем нормируем на размах аналитического решения (max - min),
# и умножаем на 100 %, чтобы получить относительную величину.
sko = 0
for i in range(0, n):
    sko += (ya[i] - ye[i])**2
sko = np.sqrt(sko / n)

skop_e = 100 * sko / (np.max(ya) - np.min(ya))
print("Отклонение от аналит.знач. skop_e =", skop_e)


# =============================================================================
# ЧАСТЬ 4. ГРАФИЧЕСКОЕ СРАВНЕНИЕ АНАЛИТИКИ И МЕТОДА ЭЙЛЕРА
# =============================================================================
plt.title("y(x)")                # заголовок графика
plt.xlabel("x")                  # подпись оси абсцисс
plt.ylabel("y")                  # подпись оси ординат
plt.grid()                       # включение сетки

# Красные звёздочки — аналитическое решение
# Чёрные звёздочки — решение методом Эйлера
plt.plot(x, ya, "r*", label="Аналитическое решение")
plt.plot(x, ye, "k*", label="Метод Эйлера")
plt.legend()
plt.show()
